/**
 * Reads `curl --help` output and writes src/lib/curlHelpData.ts.
 * Re-run when upgrading curl if help text should stay in sync.
 */
import { execSync } from 'node:child_process'
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const outPath = join(root, 'src/lib/curlHelpData.ts')

function curlHelp(arg) {
  return execSync(`curl --help ${arg ?? ''}`.trim(), { encoding: 'utf8' })
    .split('\n')
    .map((line) => line.replace(/\r$/, ''))
}

/** @returns {{ short?: string, long: string, description: string } | null} */
function parseOptionLine(line) {
  if (!line.trim() || line.startsWith('Usage:')) return null

  const topicTitle = line.match(/^([\w-]+): (.+)$/)
  if (topicTitle) return { kind: 'title', title: line.trimEnd() }

  // Category index: " auth        Different types..."
  const category = line.match(/^ ([\w-]+)\s{2,}(.+)$/)
  if (category && !category[1].startsWith('-')) {
    return { kind: 'category', name: category[1], description: category[2].trim() }
  }

  // Footer / prose lines (main help only).
  if (!/^\s*-/.test(line)) {
    const text = line.trim()
    return text ? { kind: 'footer', text } : null
  }

  // Option rows: flags, then 2+ spaces, then description.
  const match = line.match(
    /^(\s*(?:-\S+,\s+)?(?:--[\w-]+(?:\s+<[^>]+>)?(?:\[[^\]]+\])?(?:\s+\S+)*?)?)\s{2,}(.+)$/,
  )
  if (!match) return null

  const flags = match[1].trim()
  const description = match[2].trim()
  const shortLong = flags.match(/^(-\S+),\s+(--.+)$/)
  if (shortLong) {
    return { kind: 'option', short: `${shortLong[1]},`, long: shortLong[2], description }
  }
  const longOnly = flags.match(/^(--.+)$/)
  if (longOnly) return { kind: 'option', long: longOnly[1], description }

  const shortOnly = flags.match(/^(-\S+)$/)
  if (shortOnly) return { kind: 'option', short: `${shortOnly[1]},`, long: '', description }

  return null
}

function parsePage(lines, kind) {
  /** @type {any} */
  const page = { kind, options: [], categories: [], footer: [] }

  for (const line of lines) {
    const parsed = parseOptionLine(line)
    if (!parsed) continue

    switch (parsed.kind) {
      case 'title':
        page.title = parsed.title
        break
      case 'category':
        page.categories.push({ name: parsed.name, description: parsed.description })
        break
      case 'footer':
        page.footer.push(parsed.text)
        break
      case 'option':
        page.options.push({
          short: parsed.short,
          long: parsed.long,
          description: parsed.description,
        })
        break
    }
  }

  if (page.categories.length === 0) delete page.categories
  if (page.footer.length === 0) delete page.footer
  if (page.options.length === 0) delete page.options
  if (!page.title) delete page.title

  return page
}

const categoryLines = curlHelp('category')
const categoryNames = categoryLines
  .map((line) => parseOptionLine(line))
  .filter((row) => row?.kind === 'category')
  .map((row) => row.name)

/** @type {Record<string, any>} */
const pages = {
  '': parsePage(curlHelp(), 'main'),
  category: parsePage(categoryLines, 'categories'),
}

for (const name of categoryNames) {
  pages[name] = parsePage(curlHelp(name), 'topic')
}

const source = `/* eslint-disable */
// Generated by scripts/generate-curl-help.mjs — do not edit by hand.

export interface CurlHelpOption {
  short?: string
  long: string
  description: string
}

export interface CurlHelpCategory {
  name: string
  description: string
}

export type CurlHelpPage =
  | {
      kind: 'main'
      options: CurlHelpOption[]
      footer: string[]
    }
  | {
      kind: 'categories'
      categories: CurlHelpCategory[]
    }
  | {
      kind: 'topic'
      title: string
      options: CurlHelpOption[]
    }

export const CURL_HELP_CATEGORIES: CurlHelpCategory[] = ${JSON.stringify(
  pages.category.categories,
  null,
  2,
)}

export const CURL_HELP_PAGES: Record<string, CurlHelpPage> = ${JSON.stringify(pages, null, 2)}

export function curlHelpPage(name: string): CurlHelpPage {
  return CURL_HELP_PAGES[name] ?? CURL_HELP_PAGES['']
}
`

writeFileSync(outPath, source)
console.log(`Wrote ${outPath} (${Object.keys(pages).length} pages)`)
